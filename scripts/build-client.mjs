/**
 * 构建 lib/client.js：esbuild 打包 client-src/index.js（react 外部、zod 内联），
 * 再包上 DSH 客户端模块系统要求的工厂外壳（window.__ModuleLoader__.load）。
 * 外壳格式对照本机正常运行的 dsh-cost-meter lib/client.js（其 id 与包名一致）。
 *
 * 用法：
 *   node scripts/build-client.mjs                  # 就地构建（包名取本目录 package.json）
 *   node scripts/build-client.mjs --root <目录>     # 构建到另一个包目录（发布打包用）
 * 模块 id 规则：恒等于该目录 package.json 的 name（含 scope），与 cost-meter /
 * better-sidebar / dsh-mobile / @michengai/dsh-archive-manager 实测一致。
 */
import { build } from 'esbuild'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptRoot = dirname(dirname(fileURLToPath(import.meta.url)))

const argRootIndex = process.argv.indexOf('--root')
const root = argRootIndex >= 0 && process.argv[argRootIndex + 1]
  ? process.argv[argRootIndex + 1]
  : scriptRoot

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const moduleId = pkg.name
if (typeof moduleId !== 'string' || moduleId.length === 0) {
  throw new Error(`package.json 缺少合法 name（目录：${root}）`)
}

const result = await build({
  entryPoints: [join(root, 'client-src/index.js')],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'chrome120',
  external: ['react', 'react-dom', 'react-dom/client'],
  minify: true, keepNames: true,
  legalComments: 'none',
  write: false,
  jsx: 'transform',
  // 依赖（zod）从本脚本所在包解析：发布打包时 --root 指向另一个目录，
  // 那个目录没有 node_modules（依赖不随包发布）。
  nodePaths: [join(scriptRoot, 'node_modules')],
})

const body = result.outputFiles[0].text

// 工厂外壳：与 dsh-cost-meter / dsh-usage 的构建产物同构。
// CJS 产物用 require("react") 取平台种子模块；require 形参由模块系统注入。
const client = `// Generated by scripts/build-client.mjs from client-src/index.js. Do not edit directly.
window.__ModuleLoader__.load({
	id: ${JSON.stringify(moduleId)},
	factory: (require) => {
		var module = { exports: {} };
		var exports = module.exports;
		Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
		${body}
		return module.exports;
	},
});
`

mkdirSync(join(root, 'lib'), { recursive: true })
writeFileSync(join(root, 'lib', 'client.js'), client)
console.log(`built ${join(root, 'lib', 'client.js')} (${(client.length / 1024).toFixed(1)} KB) id=${moduleId}`)
