/**
 * 构建宿主半边产物：lib/host.js（源 host/index.js）与 lib/typert.js（源 typert.js）。
 *
 * 为什么要打包：zod 被内联后，包里**没有任何运行时依赖**（dependencies 为空）。
 * 实证动机（2026-10-11 真实 boot 复现）：`dsh plugin add <本地目录>` 会装成 link:，
 * 而 link: 安装**不会**安装被链接包的 dependencies —— 此时 `import { z } from 'zod'`
 * 解析失败，宿主日志出现 `todo (dsh-todo-…): failed to import`，插件整个不激活。
 * 打包后 link: / tarball / npm / 离线安装四种方式行为一致。
 *
 * 外部化：node 内置模块（esbuild platform=node 自动）、@deepseek-ai/dsh-tools 与
 * @deepseek-ai/dsh-storage-domain（由宿主 profile 提供，与官方插件一致）。
 *
 * 用法：
 *   node scripts/build-host.mjs                 # 就地构建（包名取本目录 package.json）
 *   node scripts/build-host.mjs --root <目录>    # 构建到另一个包目录（发布打包用）
 */
import { build } from 'esbuild'
import { mkdirSync, readFileSync } from 'node:fs'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptRoot = dirname(dirname(fileURLToPath(import.meta.url)))

const argRootIndex = process.argv.indexOf('--root')
const root = argRootIndex >= 0 && process.argv[argRootIndex + 1]
  ? process.argv[argRootIndex + 1]
  : scriptRoot

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const moduleId = pkg.name

const HOST_EXTERNAL = ['@deepseek-ai/dsh-tools', '@deepseek-ai/dsh-storage-domain']

async function bundleHost(entry, outfile, mustExport) {
  const result = await build({
    entryPoints: [join(root, entry)],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    external: HOST_EXTERNAL,
    minify: true,
    keepNames: true,
    legalComments: 'none',
    write: false,
    // zod 从本脚本所在包解析：发布打包时 --root 指向另一个目录（无 node_modules）。
    nodePaths: [join(scriptRoot, 'node_modules')],
  })

  const body = result.outputFiles[0].text
  const banner = `// Generated by scripts/build-host.mjs from ${entry}. Do not edit directly.\n`
  const out = banner + body

  // 导出校验只看 ESM 末尾那条 export { … } 列表，避免关键字在正文里误命中。
  const exportBlocks = [...body.matchAll(/\bexport\s*\{([^}]*)\}/g)]
  if (exportBlocks.length === 0) {
    throw new Error(`${outfile} 未见 export { … } 语句（构建异常，请检查入口 ${entry}）`)
  }
  const exported = new Set(
    exportBlocks
      .flatMap((m) => m[1].split(','))
      .map((s) => s.trim().split(/\s+as\s+/).pop().trim())
      .filter(Boolean),
  )
  for (const name of mustExport) {
    if (!exported.has(name)) {
      throw new Error(`${outfile} 缺少导出 ${name}（实际导出：${[...exported].join(', ')}）`)
    }
  }
  if (/\bfrom\s*["']zod["']|\brequire\(["']zod["']\)/.test(body)) {
    throw new Error(`${outfile} 仍引用外部 zod（应为内联）`)
  }

  mkdirSync(join(root, 'lib'), { recursive: true })
  writeFileSync(join(root, 'lib', outfile), out)
  console.log(`built ${join(root, 'lib', outfile)} (${(out.length / 1024).toFixed(1)} KB)`)
}

await bundleHost('host/index.js', 'host.js', ['name', 'inject', 'apply', 'todoDomainSpec'])
await bundleHost('typert.js', 'typert.js', ['TYPERT'])

console.log(`host bundles ready for ${moduleId}`)
